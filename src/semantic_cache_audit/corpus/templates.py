"""Hand-authored template families, one per near-miss shape per domain.

Every family here was written by hand to sit in the dangerous region of the similarity
space: two queries that an embedding model scores as near-identical and that have
genuinely different correct answers. The substitution lists are enumerated by hand as
well, so each expanded pair is an authored pair rather than a sample, and the
`provenance` field on every record names the family and the substitution it came from.

Why not sample a real query log: a log contains almost no adjacent pairs that differ in
direction, polarity, quantity or scope while remaining lexically close, because users do
not naturally produce adversarial inputs. The region that matters is therefore empty in
sampled data. ADR-001 records this and the cost it carries, which is that the corpus is
small and the resolution floor is correspondingly large.
"""

